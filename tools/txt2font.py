# txt2font.py - the game's 8x8 font, from hand-editable text to C.
#
#     python tools/txt2font.py            # tools/font/nexthack.txt -> src/font_data.h
#
# The .txt holds one glyph per block: a line "@ <hex code> <char>" and then
# eight rows of '#' (ink) and '.' (paper), MSB = leftmost pixel; ';' starts a
# comment. All 96 printable codes 0x20..0x7F must be there, once each. The
# header is generated -- edit the .txt and re-run (CI checks it is current).
#
# The font is "Byteletter" from DamienG's ZX Origins collection, modified (see
# the .txt). Its licence asks for a credit and forbids redistributing it as a
# font; here it is the game's own text, compiled into it.
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'font', 'nexthack.txt')
OUT = os.path.join(ROOT, 'src', 'font_data.h')


def parse(path):
    glyphs, code, rows = {}, None, []
    for n, raw in enumerate(open(path, encoding='utf-8'), 1):
        line = raw.split(';', 1)[0].rstrip() if not raw.startswith('@') else raw.rstrip()
        if not line:
            continue
        if line.startswith('@'):
            if code is not None:
                sys.exit('%s:%d: glyph 0x%02X has %d rows, not 8' % (path, n, code, len(rows)))
            code = int(line.split()[1], 16)
            if not 0x20 <= code <= 0x7F or code in glyphs:
                sys.exit('%s:%d: bad or repeated code 0x%02X' % (path, n, code))
            rows = []
            continue
        if code is None or len(line) != 8 or set(line) - set('#.'):
            sys.exit('%s:%d: expected 8 of # and . under an @ line: %r' % (path, n, line))
        rows.append(int(line.replace('#', '1').replace('.', '0'), 2))
        if len(rows) == 8:
            glyphs[code], code = rows, None
    if code is not None:
        sys.exit('%s: the last glyph is short' % path)
    missing = [c for c in range(0x20, 0x80) if c not in glyphs]
    if missing:
        sys.exit('%s: missing codes %s' % (path, ' '.join('0x%02X' % c for c in missing)))
    return glyphs


def main():
    g = parse(SRC)
    out = ['/* GENERATED by tools/txt2font.py from tools/font/nexthack.txt -- do not',
           ' * edit; edit the .txt and re-run the tool.',
           ' *',
           ' * The game\'s 8x8 font: "Byteletter" from the ZX Origins collection by',
           ' * DamienG (https://damieng.com/zx-origins), modified for NextHack -- the',
           ' * .txt lists the changes. Codes 32..127 (127 = copyright sign), 8 bytes',
           ' * each, top row first, MSB = leftmost pixel. Read once, at boot, by',
           ' * platform_init.c: the Next expands it into its text tiles, the 128K',
           ' * copies it to font_ram in Bank 5. */',
           '#ifndef FONT_DATA_H',
           '#define FONT_DATA_H',
           '',
           'static const uint8_t font_data[96 * 8] = {']
    for c in range(0x20, 0x80):
        name = chr(c) if chr(c).isalnum() else ''
        out.append('    %s,  /* 0x%02X %s*/' % (','.join('0x%02X' % b for b in g[c]), c,
                                              (name + ' ') if name else ''))
    out += ['};', '', '#endif', '']
    text = '\n'.join(out)
    if os.path.exists(OUT) and open(OUT, encoding='utf-8', newline='').read().replace('\r\n', '\n') == text:
        print('txt2font: %s is up to date' % os.path.relpath(OUT, ROOT))
        return
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print('txt2font: wrote %s (96 glyphs)' % os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
