# txt2template.py - pack the hand-drawn special-level maps in
# tools/templates/*.txt into src/leveltmpl_data.h (banked const).
#
#   python tools/txt2template.py
#
# Each .txt is a MAPH x MAPW ASCII map using the normal terrain chars
# ('.' '#' '-' '|' '+' '<' '>' ' '), preceded by metadata comment lines:
#   ;name:  <label>                      (optional, for the C comment)
#   ;rooms: x,y,w,h [x,y,w,h ...]        (1..3 room rects FOV should light)
# Rows shorter than MAPW are padded with rock; missing trailing rows are rock.

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lztmpl

HERE = Path(__file__).resolve().parent
TDIR = HERE / "templates"
OUT  = HERE.parent / "src" / "leveltmpl_data.h"
MAPW, MAPH = 80, 21
MAXROOM = 6


def load(path):
    name = path.stem
    rooms, rows = [], []
    for line in path.read_text().splitlines():
        if line.startswith(";rooms:"):
            rooms = [tuple(int(v) for v in tok.split(","))
                     for tok in line[len(";rooms:"):].split()]
        elif line.startswith(";"):
            continue
        else:
            rows.append(line)
    if len(rows) > MAPH:
        raise SystemExit(f"{name}: {len(rows)} map rows > {MAPH}")
    rows += [""] * (MAPH - len(rows))                 # pad trailing rock rows
    grid = []
    for i, r in enumerate(rows):
        if len(r) > MAPW:
            raise SystemExit(f"{name}: row {i} is {len(r)} > {MAPW} cols")
        grid.append(r.ljust(MAPW))
    if not (1 <= len(rooms) <= MAXROOM):
        raise SystemExit(f"{name}: need 1..{MAXROOM} room rects, got {len(rooms)}")
    for (x, y, w, h) in rooms:
        if x + w > MAPW or y + h > MAPH:
            raise SystemExit(f"{name}: room {x},{y},{w},{h} out of bounds")
    return name, grid, rooms


def main():
    tmpls = [load(p) for p in sorted(TDIR.glob("*.txt"))]
    if not tmpls:
        raise SystemExit("no templates in " + str(TDIR))
    with OUT.open("w", newline="\n") as f:
        f.write("/* SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write(" * Copyright (C) 2026 Leonardo Roman da Rosa */\n")
        f.write("/* leveltmpl_data.h - GENERATED by tools/txt2template.py from\n")
        f.write(" * tools/templates/*.txt. Do not edit by hand. Hand-drawn special-\n")
        f.write(" * level maps (MAPH x MAPW) + their room rects, included once into\n")
        f.write(" * the banked leveltmpl.c as const; banks.json says which\n")
        f.write(" * bank, and load_template() runs from that same one. */\n\n")
        f.write("#define NTMPL %d\n\n" % len(tmpls))

        # The grids are LZ-packed (tools/lztmpl.py) and expanded straight into
        # lvl[][] by load_template, which was going to write those 1680 bytes
        # anyway -- so the destination costs nothing and the bank keeps the
        # difference: 8400 B of grids become about a tenth of that.
        blobs, offs = [], []
        for name, grid, _ in tmpls:
            data = "".join(grid).encode("latin1")
            blob = lztmpl.compress(data)
            if lztmpl.expand(blob, len(data)) != data:     # never ship a guess
                raise SystemExit(name + ": LZ round-trip failed")
            offs.append(sum(len(b) for b in blobs))
            blobs.append(blob)

        f.write("/* One LZ stream per template; lz_expand() (platform.c, called\n"
                " * by leveltmpl.c) unpacks it directly into lvl[][]. */\n")
        f.write("static const uint8_t tmpl_lz[] = {\n")
        for (name, _, _), blob in zip(tmpls, blobs):
            f.write("  /* %s: %d B */\n" % (name, len(blob)))
            for i in range(0, len(blob), 16):
                f.write("  " + ",".join(str(b) for b in blob[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint16_t tmpl_off[NTMPL] = { %s };\n\n"
                % ", ".join(str(o) for o in offs))

        f.write("static const uint8_t tmpl_nroom[NTMPL] = { %s };\n\n"
                % ", ".join(str(len(r)) for _, _, r in tmpls))

        f.write("static const uint8_t tmpl_room[NTMPL][%d][4] = {\n" % MAXROOM)
        for name, _, rooms in tmpls:
            cells = ["{%d,%d,%d,%d}" % r for r in rooms]
            cells += ["{0,0,0,0}"] * (MAXROOM - len(cells))
            f.write("  { " + ", ".join(cells) + " },\n")
        f.write("};\n")

    packed = sum(len(b) for b in blobs)
    raw = len(tmpls) * MAPW * MAPH
    print("wrote %s  (%d template(s): %s)"
          % (OUT, len(tmpls), ", ".join(n for n, _, _ in tmpls)))
    print("  grids %d B -> %d B packed (%.1f%%), round-trip verified"
          % (raw, packed, 100.0 * packed / raw))
    astral()


# The Astral Plane (2.0) is drawn the same way but kept OUT of templates/, so
# the random template pool -- and with it every existing world -- never sees
# it. It packs into its own header, read by ascend.c from ascend.c's bank.
# '@' marks where the hero arrives: there are no stairs on the plane (a '<'
# there would lead to dlvl 54, the mines' bottom), so the cell is floor and
# its place travels as two constants. The altars' order matters to the
# resident altar_align (level.c), which tells the three apart by x / 27.
ASTRAL_SRC = HERE / "astral.txt"
ASTRAL_OUT = HERE.parent / "src" / "astral_data.h"


def astral():
    name, grid, rooms = load(ASTRAL_SRC)
    arrive = [(x, y) for y, r in enumerate(grid) for x, c in enumerate(r) if c == "@"]
    altars = [(x, y) for y, r in enumerate(grid) for x, c in enumerate(r) if c == "_"]
    if len(arrive) != 1:
        raise SystemExit("astral: need exactly one '@' (the arrival), got %d" % len(arrive))
    if [x // 27 for x, _ in sorted(altars)] != [0, 1, 2]:
        raise SystemExit("astral: need three altars, one in each third (x // 27 = 0, 1, 2)")
    if any(c in "<>+" for r in grid for c in r):
        raise SystemExit("astral: no stairs and no doors on the plane")
    if len(rooms) != 4:
        raise SystemExit("astral: rooms are the three temples, then the field")
    for (ax, ay), (x, y, w, h) in zip(sorted(altars), rooms):
        if not (x < ax < x + w - 1 and y < ay - 1 and ay < y + h - 1):
            raise SystemExit("astral: altar (%d,%d) is not inside temple %d,%d,%d,%d "
                             "with a row above it for the priest" % (ax, ay, x, y, w, h))
    # place_altar and place_fountain (nexthack_lvl.c) run on every level and
    # drop theirs on a hashed room's centre when it is plain floor. Here every
    # centre is taken -- the temples' by their altars, the field's by a
    # pillar -- so the plane never grows a fourth altar or a fountain.
    for (x, y, w, h) in rooms:
        if grid[y + h // 2][x + w // 2] == ".":
            raise SystemExit("astral: the centre of room %d,%d,%d,%d is plain floor, "
                             "where place_altar/place_fountain would put theirs"
                             % (x, y, w, h))
    ux, uy = arrive[0]
    grid = [r.replace("@", ".") for r in grid]
    data = "".join(grid).encode("latin1")
    blob = lztmpl.compress(data)
    if lztmpl.expand(blob, len(data)) != data:
        raise SystemExit("astral: LZ round-trip failed")
    with ASTRAL_OUT.open("w", newline="\n") as f:
        f.write("/* SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write(" * Copyright (C) 2026 Leonardo Roman da Rosa */\n")
        f.write("/* astral_data.h - GENERATED by tools/txt2template.py from\n")
        f.write(" * tools/astral.txt. Do not edit by hand. The Astral Plane's map,\n")
        f.write(" * LZ-packed, its rooms (the three temples, then the field) and\n")
        f.write(" * where the hero arrives; included once into the banked ascend.c\n")
        f.write(" * as const. */\n\n")
        f.write("#define ASTRAL_UP_X %d\n" % ux)
        f.write("#define ASTRAL_UP_Y %d\n" % uy)
        f.write("#define ASTRAL_NROOM %d   /* temples 0..2, the field last */\n\n"
                % len(rooms))
        f.write("static const uint8_t astral_lz[] = {   /* %d B */\n" % len(blob))
        for i in range(0, len(blob), 16):
            f.write("  " + ",".join(str(b) for b in blob[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("static const uint8_t astral_room[ASTRAL_NROOM][4] = {\n")
        f.write("  " + ", ".join("{%d,%d,%d,%d}" % r for r in rooms) + "\n};\n\n")
        f.write("/* the altars, temple by temple (each priest stands on the row above) */\n")
        f.write("static const uint8_t astral_altar[3][2] = { %s };\n"
                % ", ".join("{%d,%d}" % a for a in sorted(altars)))
    print("wrote %s  (%d B packed, arrival %d,%d)" % (ASTRAL_OUT, len(blob), ux, uy))


if __name__ == "__main__":
    main()
